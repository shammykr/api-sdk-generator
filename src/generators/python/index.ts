import type { ApiSpec, EnumValue, Model, Operation, Parameter, TypeRef } from "../../parser/types.js";
import { pascalCase, snakeCase, uniqueName, upperSnakeCase } from "../../utils/naming.js";
import { generateMarkdownDocs, type DocStyle } from "../docs/markdown.js";
import { clientClassName, finalize, type GeneratedFile, type Generator } from "../types.js";

/**
 * Python target. The output directory is an importable package:
 *
 *   __init__.py       – re-exports
 *   models.py         – Pydantic v2 models, Enums and type aliases
 *   client.py         – httpx-based client with type hints and ApiError
 *   requirements.txt  – runtime dependencies (httpx, pydantic)
 *   API.md            – markdown reference
 */
export const pythonGenerator: Generator = {
  language: "python",
  generate(spec: ApiSpec): GeneratedFile[] {
    const className = clientClassName(spec, pascalCase);
    return [
      {
        path: "__init__.py",
        contents: finalize([
          header(spec),
          "from . import models",
          `from .client import DEFAULT_BASE_URL, ApiError, ${className}`,
          "from .models import *  # noqa: F401,F403",
        ]),
      },
      { path: "models.py", contents: renderModels(spec) },
      { path: "client.py", contents: renderClient(spec, className) },
      { path: "requirements.txt", contents: "httpx>=0.27\npydantic>=2.6\n" },
      { path: "API.md", contents: generateMarkdownDocs(spec, docStyle(spec, className)) },
    ];
  },
};

const PY_KEYWORDS = new Set([
  "False", "None", "True", "and", "as", "assert", "async", "await", "break", "class", "continue",
  "def", "del", "elif", "else", "except", "finally", "for", "from", "global", "if", "import", "in",
  "is", "lambda", "nonlocal", "not", "or", "pass", "raise", "return", "try", "while", "with", "yield",
]);
/** Attribute names that would shadow pydantic.BaseModel members. */
const BASEMODEL_ATTRS = new Set(["json", "dict", "copy", "schema", "validate", "construct", "parse_obj", "fields"]);

function pyIdent(raw: string, extraReserved: Set<string> = new Set()): string {
  let name = snakeCase(raw) || "value";
  if (name.startsWith("model_")) name = `field_${name}`;
  if (PY_KEYWORDS.has(name) || extraReserved.has(name)) name += "_";
  return name;
}

function header(spec: ApiSpec): string {
  return `# Code generated by api-sdk-generator from "${spec.title}" v${spec.version}. DO NOT EDIT.`;
}

function pyLiteral(v: EnumValue): string {
  if (typeof v === "boolean") return v ? "True" : "False";
  return typeof v === "string" ? JSON.stringify(v) : String(v);
}

function pyDoc(text: string | undefined, indent: string): string[] {
  if (!text) return [];
  const safe = text.replace(/\\/g, "\\\\").replace(/"""/g, '\\"\\"\\"').trim();
  const lines = safe.split("\n");
  if (lines.length === 1) return [`${indent}"""${lines[0]}"""`];
  return [`${indent}"""${lines[0]}`, ...lines.slice(1).map((l) => (l ? indent + l : "")), `${indent}"""`];
}

// ------------------------------------------------------------------ types

/** Render a TypeRef as a Python type hint. `prefix` qualifies model names (e.g. "m."). */
export function pyType(t: TypeRef, prefix = ""): string {
  let s: string;
  switch (t.kind) {
    case "primitive":
      s = { string: "str", integer: "int", number: "float", boolean: "bool", null: "None", unknown: "Any" }[t.name];
      break;
    case "array":
      s = `List[${pyType(t.items, prefix)}]`;
      break;
    case "map":
      s = `Dict[str, ${pyType(t.values, prefix)}]`;
      break;
    case "ref":
      s = `${prefix}${t.name}`;
      break;
    case "enum":
      s = t.values.length ? `Literal[${t.values.map(pyLiteral).join(", ")}]` : "Any";
      break;
    case "union":
      s = `Union[${t.variants.map((v) => pyType(v, prefix)).join(", ")}]`;
      break;
  }
  return t.nullable && s !== "None" && s !== "Any" ? `Optional[${s}]` : s;
}

function isOptionalHint(t: TypeRef): boolean {
  return !!t.nullable || (t.kind === "primitive" && (t.name === "unknown" || t.name === "null"));
}

function refsIn(t: TypeRef, acc: Set<string> = new Set()): Set<string> {
  if (t.kind === "ref") acc.add(t.name);
  if (t.kind === "array") refsIn(t.items, acc);
  if (t.kind === "map") refsIn(t.values, acc);
  if (t.kind === "union") t.variants.forEach((v) => refsIn(v, acc));
  return acc;
}

// ----------------------------------------------------------------- models

function enumBase(values: EnumValue[]): "str" | "int" | "float" | undefined {
  if (values.length === 0) return undefined;
  if (values.every((v) => typeof v === "string")) return "str";
  if (values.every((v) => typeof v === "number" && Number.isInteger(v))) return "int";
  if (values.every((v) => typeof v === "number")) return "float";
  return undefined;
}

function enumMemberNames(values: EnumValue[]): string[] {
  const taken = new Set<string>();
  return values.map((v, i) => {
    let name = upperSnakeCase(String(v));
    if (!name || /^_?[0-9]/.test(name)) name = `VALUE_${name.replace(/^_/, "") || i}`;
    if (typeof v === "number" && v < 0) name = `MINUS_${name}`;
    if (PY_KEYWORDS.has(name)) name += "_";
    name = uniqueName(name, taken);
    taken.add(name);
    return name;
  });
}

/**
 * Order: Enums, then classes (annotations are lazy thanks to
 * `from __future__ import annotations`), then aliases topologically sorted
 * (aliases are evaluated eagerly), then model_rebuild() for every class.
 */
function renderModels(spec: ApiSpec): string {
  const enums: string[] = [];
  const classes: string[] = [];
  const aliasModels: Extract<Model, { kind: "alias" }>[] = [];
  const classNames: string[] = [];

  for (const model of spec.models) {
    if (model.kind === "enum") {
      const base = enumBase(model.values);
      if (!base) {
        aliasModels.push({ kind: "alias", name: model.name, description: model.description, type: { kind: "enum", values: model.values } });
        continue;
      }
      const members = enumMemberNames(model.values);
      enums.push(`class ${model.name}(${base}, Enum):`, ...pyDoc(model.description, "    "));
      model.values.forEach((v, i) => enums.push(`    ${members[i]} = ${pyLiteral(v)}`));
      enums.push("", "");
    } else if (model.kind === "alias") {
      aliasModels.push(model);
    } else {
      classNames.push(model.name);
      classes.push(...renderClass(model), "", "");
    }
  }

  const aliases: string[] = [];
  for (const alias of topoSortAliases(aliasModels)) {
    aliases.push(`${alias.name} = ${pyType(alias.type)}`);
    if (alias.description) aliases.push(...pyDoc(alias.description, ""));
    aliases.push("");
  }

  const exported = spec.models.map((m) => JSON.stringify(m.name));
  const out = [
    header(spec),
    "from __future__ import annotations",
    "",
    "from enum import Enum",
    "from typing import Any, Dict, List, Literal, Optional, Union",
    "",
    "from pydantic import BaseModel, ConfigDict, Field",
    "",
    `__all__ = [${exported.join(", ")}]`,
    "",
    "",
    "class _Model(BaseModel):",
    '    """Base for all generated models: accepts both wire names and Python names."""',
    "",
    "    model_config = ConfigDict(populate_by_name=True)",
    "",
    "",
    ...enums,
    ...classes,
    ...aliases,
    "",
    ...classNames.map((n) => `${n}.model_rebuild()`),
  ];
  return finalize(out, 2);
}

function renderClass(model: Extract<Model, { kind: "object" }>): string[] {
  const lines = [`class ${model.name}(_Model):`, ...pyDoc(model.description, "    ")];
  if (model.additionalProperties) {
    if (model.description) lines.push("");
    lines.push('    model_config = ConfigDict(populate_by_name=True, extra="allow")');
  }
  if (model.properties.length === 0 && !model.additionalProperties && !model.description) lines.push("    pass");
  if (model.properties.length && (model.description || model.additionalProperties)) lines.push("");

  const taken = new Set<string>();
  for (const p of model.properties) {
    const field = uniqueName(pyIdent(p.name, BASEMODEL_ATTRS), taken);
    taken.add(field);
    let hint = pyType(p.type);
    const args: string[] = [];
    if (!p.required) {
      if (!isOptionalHint(p.type)) hint = `Optional[${hint}]`;
      args.push("default=None");
    }
    if (field !== p.name) args.push(`alias=${JSON.stringify(p.name)}`);
    if (p.description) args.push(`description=${JSON.stringify(p.description)}`);
    let line = `    ${field}: ${hint}`;
    if (args.length === 1 && args[0] === "default=None") line += " = None";
    else if (args.length) line += ` = Field(${args.join(", ")})`;
    lines.push(line);
  }
  return lines;
}

function topoSortAliases(aliases: Extract<Model, { kind: "alias" }>[]): Extract<Model, { kind: "alias" }>[] {
  const byName = new Map(aliases.map((a) => [a.name, a]));
  const done = new Set<string>();
  const visiting = new Set<string>();
  const out: Extract<Model, { kind: "alias" }>[] = [];
  const visit = (a: Extract<Model, { kind: "alias" }>) => {
    if (done.has(a.name) || visiting.has(a.name)) return;
    visiting.add(a.name);
    for (const dep of [...refsIn(a.type)].sort()) {
      const d = byName.get(dep);
      if (d) visit(d);
    }
    visiting.delete(a.name);
    done.add(a.name);
    out.push(a);
  };
  aliases.forEach(visit);
  return out;
}

// ----------------------------------------------------------------- client

const RUNTIME = `class ApiError(Exception):
    """Raised for every non-2xx response.

    \`\`body\`\` holds the parsed response body, validated against the
    operation's documented error type when it matches.
    """

    def __init__(self, status_code: int, body: Any, response: httpx.Response) -> None:
        super().__init__(f"Request failed with status {status_code}")
        self.status_code = status_code
        self.body = body
        self.response = response


def _scalar(value: Any) -> Any:
    if isinstance(value, Enum):
        return value.value
    if isinstance(value, bool):
        return "true" if value else "false"
    return value


def _query(values: Mapping[str, Any]) -> Dict[str, Any]:
    out: Dict[str, Any] = {}
    for key, value in values.items():
        if value is None:
            continue
        out[key] = [_scalar(v) for v in value] if isinstance(value, (list, tuple)) else _scalar(value)
    return out


def _headers(values: Mapping[str, Any]) -> Dict[str, str]:
    return {key: str(_scalar(value)) for key, value in values.items() if value is not None}


def _path(value: Any) -> str:
    return quote(str(_scalar(value)), safe="")


def _parse(response: httpx.Response, type_: Any, strict: bool) -> Any:
    if response.status_code == 204 or not response.content:
        return None
    if "json" not in response.headers.get("content-type", ""):
        return response.text
    data = response.json()
    if type_ is None:
        return data
    try:
        return TypeAdapter(type_).validate_python(data)
    except ValidationError:
        if strict:
            raise
        return data`;

const REQUEST_METHOD = `    def _request(
        self,
        method: str,
        path: str,
        *,
        query: Optional[Mapping[str, Any]] = None,
        headers: Optional[Mapping[str, Any]] = None,
        body: Any = None,
        body_type: Any = None,
        content_type: Optional[str] = None,
        response_type: Any = None,
        error_type: Any = None,
    ) -> Any:
        request_headers = _headers(headers or {})
        kwargs: Dict[str, Any] = {}
        if body is not None:
            if content_type and "json" in content_type:
                adapter = TypeAdapter(body_type if body_type is not None else Any)
                payload = adapter.dump_python(
                    adapter.validate_python(body), mode="json", by_alias=True, exclude_unset=True
                )
                kwargs["content"] = json.dumps(payload).encode("utf-8")
            else:
                kwargs["content"] = body
            if content_type and not content_type.startswith("multipart/"):
                request_headers["Content-Type"] = content_type
        response = self._client.request(
            method, path, params=_query(query or {}), headers=request_headers, **kwargs
        )
        if response.is_error:
            raise ApiError(response.status_code, _parse(response, error_type, strict=False), response)
        return _parse(response, response_type, strict=True)`;

interface PyParam {
  param: Parameter;
  ident: string;
}

function pyParams(op: Operation): PyParam[] {
  const taken = new Set(["self", "body", "m"]);
  return op.parameters.map((param) => {
    const ident = uniqueName(pyIdent(param.name, taken), taken);
    taken.add(ident);
    return { param, ident };
  });
}

function methodName(op: Operation): string {
  return pyIdent(op.id, new Set(["close"]));
}

function renderClient(spec: ApiSpec, className: string): string {
  const out = [
    header(spec),
    "from __future__ import annotations",
    "",
    "import json",
    "from enum import Enum",
    "from typing import Any, Dict, List, Literal, Mapping, Optional, Union",
    "from urllib.parse import quote",
    "",
    "import httpx",
    "from pydantic import TypeAdapter, ValidationError",
    "",
    "from . import models as m",
    "",
    "__all__ = [\"DEFAULT_BASE_URL\", \"ApiError\", " + JSON.stringify(className) + "]",
    "",
    "#: Default base URL, taken from the spec's first server entry.",
    `DEFAULT_BASE_URL = ${JSON.stringify(spec.baseUrl)}`,
    "",
    "",
    RUNTIME,
    "",
    "",
    `class ${className}:`,
    ...pyDoc(`Typed client for ${spec.title} v${spec.version}.\n\nUse as a context manager (\`\`with ${className}() as client:\`\`) or call close().`, "    "),
    "",
    "    def __init__(",
    "        self,",
    "        base_url: str = DEFAULT_BASE_URL,",
    "        *,",
    "        headers: Optional[Mapping[str, str]] = None,",
    "        timeout: float = 30.0,",
    "        http_client: Optional[httpx.Client] = None,",
    "    ) -> None:",
    "        self._client = http_client or httpx.Client(",
    '            base_url=base_url, headers={"Accept": "application/json", **(headers or {})}, timeout=timeout',
    "        )",
    "",
    "    def close(self) -> None:",
    "        self._client.close()",
    "",
    `    def __enter__(self) -> "${className}":`,
    "        return self",
    "",
    "    def __exit__(self, *exc_info: Any) -> None:",
    "        self.close()",
    "",
  ];
  for (const op of spec.operations) out.push(...renderMethod(op), "");
  out.push(REQUEST_METHOD);
  return finalize(out, 2);
}

function renderMethod(op: Operation): string[] {
  const params = pyParams(op);
  const positional: string[] = [];
  const keywordRequired: string[] = [];
  const keywordOptional: string[] = [];
  for (const { param, ident } of params) {
    const hint = pyType(param.type, "m.");
    if (param.in === "path") positional.push(`${ident}: ${hint}`);
    else if (param.required) keywordRequired.push(`${ident}: ${hint}`);
    else keywordOptional.push(`${ident}: ${isOptionalHint(param.type) ? hint : `Optional[${hint}]`} = None`);
  }
  if (op.requestBody) {
    const hint = pyType(op.requestBody.type, "m.");
    positional.push(
      op.requestBody.required ? `body: ${hint}` : `body: ${isOptionalHint(op.requestBody.type) ? hint : `Optional[${hint}]`} = None`,
    );
  }
  const keyword = [...keywordRequired, ...keywordOptional];
  const signature = ["self", ...positional, ...(keyword.length ? ["*", ...keyword] : [])];
  const returnType = op.successType ? pyType(op.successType, "m.") : "None";
  const errorType = op.errorTypes.length === 0
    ? undefined
    : op.errorTypes.length === 1
      ? pyType(op.errorTypes[0], "m.")
      : `Union[${op.errorTypes.map((t) => pyType(t, "m.")).join(", ")}]`;

  const docParts = [
    op.summary,
    op.description && op.description !== op.summary ? op.description : undefined,
    `\`\`${op.method.toUpperCase()} ${op.path}\`\``,
    op.deprecated ? ".. deprecated:: This operation is deprecated." : undefined,
    `Raises:\n    ApiError: on a non-2xx response${errorType ? `; \`\`body\`\` is \`\`${errorType}\`\`` : ""}.`,
  ].filter(Boolean);

  const lines = [`    def ${methodName(op)}(`];
  for (const s of signature) lines.push(`        ${s},`);
  lines.push(`    ) -> ${returnType}:`);
  lines.push(...pyDoc(docParts.join("\n\n"), "        "));

  const pathExpr = op.path.replace(/\{([^}]+)\}/g, (match, name: string) => {
    const p = params.find((x) => x.param.in === "path" && x.param.name === name);
    return p ? `{_path(${p.ident})}` : match;
  });
  const fstring = /\{_path\(/.test(pathExpr);
  const pathLiteral = fstring
    ? `f${JSON.stringify(pathExpr.replace(/\{(?!_path\()/g, "{{").replace(/(?<!\))\}/g, "}}"))}`
    : JSON.stringify(op.path);
  const dict = (where: string) =>
    params
      .filter((p) => p.param.in === where)
      .map((p) => `${JSON.stringify(p.param.name)}: ${p.ident}`)
      .join(", ");

  const call = [`            ${JSON.stringify(op.method.toUpperCase())},`, `            ${pathLiteral},`];
  if (dict("query")) call.push(`            query={${dict("query")}},`);
  if (dict("header")) call.push(`            headers={${dict("header")}},`);
  if (op.requestBody) {
    call.push("            body=body,");
    call.push(`            body_type=${pyType(op.requestBody.type, "m.")},`);
    call.push(`            content_type=${JSON.stringify(op.requestBody.contentType)},`);
  }
  if (op.successType) call.push(`            response_type=${returnType},`);
  if (errorType) call.push(`            error_type=${errorType},`);
  lines.push(`        ${op.successType ? "return " : ""}self._request(`, ...call, "        )");
  return lines;
}

// ------------------------------------------------------------------- docs

function sample(t: TypeRef, spec: ApiSpec): string {
  switch (t.kind) {
    case "primitive":
      return { string: '"string"', integer: "1", number: "1.5", boolean: "True", null: "None", unknown: "{}" }[t.name];
    case "enum":
      return t.values.length ? pyLiteral(t.values[0]) : "None";
    case "array":
      return `[${sample(t.items, spec)}]`;
    case "map":
      return "{}";
    case "union":
      return sample(t.variants[0], spec);
    case "ref": {
      const m = spec.models.find((x) => x.name === t.name);
      if (m?.kind === "enum") return enumBase(m.values) ? `${m.name}.${enumMemberNames(m.values)[0]}` : pyLiteral(m.values[0]);
      if (m?.kind === "alias") return sample(m.type, spec);
      if (m?.kind === "object") {
        const req = m.properties.filter((p) => p.required);
        const taken = new Set<string>();
        const args = req.map((p) => {
          const f = uniqueName(pyIdent(p.name, BASEMODEL_ATTRS), taken);
          taken.add(f);
          return `${f}=${sample(p.type, spec)}`;
        });
        return `${m.name}(${args.join(", ")})`;
      }
      return "None";
    }
  }
}

function docStyle(spec: ApiSpec, className: string): DocStyle {
  return {
    language: "Python",
    fence: "python",
    renderType: (t) => pyType(t),
    methodName,
    paramName: (name) => pyIdent(name),
    setup: [
      `from sdk import ${className}, ApiError  # "sdk" = the generated package directory`,
      "from sdk.models import *",
      "",
      `client = ${className}(`,
      `    ${JSON.stringify(spec.baseUrl || "https://api.example.com")},`,
      '    headers={"Authorization": "Bearer <token>"},',
      ")",
    ].join("\n"),
    example(op) {
      const params = pyParams(op);
      const args: string[] = [];
      for (const { param } of params) {
        if (param.in === "path") args.push(sample(param.type, spec));
      }
      const lines: string[] = [];
      if (op.requestBody) {
        lines.push(`body = ${sample(op.requestBody.type, spec)}`);
        args.push("body");
      }
      for (const { param, ident } of params) {
        if (param.in !== "path" && param.required) args.push(`${ident}=${sample(param.type, spec)}`);
      }
      const call = `client.${methodName(op)}(${args.join(", ")})`;
      lines.push("try:", `    ${op.successType ? "result = " : ""}${call}`, "except ApiError as err:", "    print(err.status_code, err.body)");
      return lines.join("\n");
    },
  };
}

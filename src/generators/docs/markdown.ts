import type { ApiSpec, Model, Operation, TypeRef } from "../../parser/types.js";
import { finalize } from "../types.js";

/** Language-specific hooks used by the shared markdown reference generator. */
export interface DocStyle {
  /** Human name of the language, e.g. "TypeScript". */
  language: string;
  /** Code fence info string, e.g. "ts". */
  fence: string;
  renderType(t: TypeRef): string;
  methodName(op: Operation): string;
  paramName(name: string): string;
  /** Snippet showing how to construct the client. */
  setup: string;
  /** Snippet showing a call to `op`. */
  example(op: Operation): string;
}

/**
 * Build API.md: an endpoint index, one section per endpoint (parameters,
 * request body, responses, example call) and one section per model.
 * Types are rendered in the syntax of the SDK the doc ships with.
 */
export function generateMarkdownDocs(spec: ApiSpec, style: DocStyle): string {
  const out: string[] = [];
  const code = (s: string) => `\`${s.replace(/\|/g, "\\|")}\``;
  const cell = (s?: string) => (s ?? "").replace(/\r?\n+/g, " ").replace(/\|/g, "\\|").trim() || "—";
  const anchor = (s: string) => s.toLowerCase().replace(/[^a-z0-9 _-]/g, "").replace(/ /g, "-");

  out.push(`# ${spec.title} — ${style.language} SDK reference`, "");
  out.push(
    `> Generated by api-sdk-generator from **${spec.title}** v${spec.version} (OpenAPI ${spec.openapiVersion}). Do not edit by hand.`,
    "",
  );
  if (spec.description) out.push(spec.description, "");

  out.push("## Setup", "", "```" + style.fence, style.setup, "```", "");

  out.push("## Endpoints", "", "| Method | Path | Client method | Summary |", "| --- | --- | --- | --- |");
  for (const op of spec.operations) {
    const name = style.methodName(op);
    out.push(
      `| ${op.method.toUpperCase()} | ${code(op.path)} | [${code(name)}](#${anchor(name)}) | ${cell(op.summary)}${op.deprecated ? " _(deprecated)_" : ""} |`,
    );
  }
  out.push("");

  for (const op of spec.operations) {
    out.push(`### ${style.methodName(op)}`, "", `\`${op.method.toUpperCase()} ${op.path}\``, "");
    if (op.deprecated) out.push("> **Deprecated.**", "");
    if (op.summary) out.push(`**${op.summary}**`, "");
    if (op.description && op.description !== op.summary) out.push(op.description, "");
    if (op.tags.length) out.push(`Tags: ${op.tags.join(", ")}`, "");

    if (op.parameters.length) {
      out.push("**Parameters**", "", "| Name | In | Type | Required | Description |", "| --- | --- | --- | --- | --- |");
      for (const p of op.parameters) {
        const display = style.paramName(p.name) === p.name ? code(p.name) : `${code(style.paramName(p.name))} (\`${p.name}\`)`;
        out.push(`| ${display} | ${p.in} | ${code(style.renderType(p.type))} | ${p.required ? "yes" : "no"} | ${cell(p.description)} |`);
      }
      out.push("");
    } else {
      out.push("**Parameters**: none", "");
    }

    if (op.requestBody) {
      const b = op.requestBody;
      out.push(
        `**Request body** (${b.required ? "required" : "optional"}, \`${b.contentType}\`): ${code(style.renderType(b.type))}${b.description ? ` — ${cell(b.description)}` : ""}`,
        "",
      );
    }

    out.push("**Responses**", "", "| Status | Type | Description |", "| --- | --- | --- |");
    for (const r of op.responses) {
      out.push(`| ${r.status} | ${r.type ? code(style.renderType(r.type)) : "—"} | ${cell(r.description)} |`);
    }
    out.push("");
    if (op.errorTypes.length) {
      out.push(
        `Non-2xx responses raise \`ApiError\` whose body is ${op.errorTypes.map((t) => code(style.renderType(t))).join(" or ")}.`,
        "",
      );
    }

    out.push("**Example**", "", "```" + style.fence, style.example(op), "```", "");
  }

  if (spec.models.length) {
    out.push("## Models", "");
    for (const m of spec.models) out.push(...renderModel(m, style, code, cell));
  }
  return finalize(out);
}

function renderModel(
  m: Model,
  style: DocStyle,
  code: (s: string) => string,
  cell: (s?: string) => string,
): string[] {
  const out = [`### ${m.name}`, ""];
  if (m.description) out.push(m.description, "");
  if (m.kind === "enum") {
    out.push(`Enum of: ${m.values.map((v) => code(JSON.stringify(v))).join(", ")}`, "");
  } else if (m.kind === "alias") {
    const kind = m.type.kind === "union" ? ` (${m.type.mode})` : "";
    out.push(`Type${kind}: ${code(style.renderType(m.type))}`, "");
  } else {
    if (m.properties.length) {
      out.push("| Property | Type | Required | Description |", "| --- | --- | --- | --- |");
      for (const p of m.properties) {
        out.push(`| ${code(p.name)} | ${code(style.renderType(p.type))} | ${p.required ? "yes" : "no"} | ${cell(p.description)} |`);
      }
      out.push("");
    }
    if (m.additionalProperties) {
      out.push(`Additional properties: ${code(style.renderType(m.additionalProperties))}`, "");
    }
  }
  return out;
}

import type { ApiSpec, Model, Operation, TypeRef } from "../../parser/types.js";
import { camelCase, isValidJsIdentifier, pascalCase, uniqueName } from "../../utils/naming.js";
import { generateMarkdownDocs, type DocStyle } from "../docs/markdown.js";
import { clientClassName, finalize, type GeneratedFile, type Generator } from "../types.js";

/**
 * TypeScript target. Emits a dependency-free, fetch-based client:
 *
 *   models.ts  – interfaces / type aliases for every schema
 *   client.ts  – typed params, typed error aliases, ApiError, the client class
 *   index.ts   – re-exports
 *   API.md     – markdown reference
 */
export const typescriptGenerator: Generator = {
  language: "typescript",
  generate(spec: ApiSpec): GeneratedFile[] {
    const names = new OperationNames(spec);
    return [
      { path: "models.ts", contents: renderModels(spec) },
      { path: "client.ts", contents: renderClient(spec, names) },
      {
        path: "index.ts",
        contents: finalize([header(spec), "", 'export * from "./models.js";', 'export * from "./client.js";']),
      },
      { path: "API.md", contents: generateMarkdownDocs(spec, docStyle(spec)) },
    ];
  },
};

// ------------------------------------------------------------------ types

/** Render a TypeRef as TypeScript. `prefix` qualifies model references (e.g. "M."). */
export function tsType(t: TypeRef, prefix = ""): string {
  let s: string;
  switch (t.kind) {
    case "primitive":
      s = { string: "string", integer: "number", number: "number", boolean: "boolean", null: "null", unknown: "unknown" }[t.name];
      break;
    case "array": {
      const inner = tsType(t.items, prefix);
      s = isCompound(t.items) ? `Array<${inner}>` : `${inner}[]`;
      break;
    }
    case "map":
      s = `Record<string, ${tsType(t.values, prefix)}>`;
      break;
    case "ref":
      s = `${prefix}${t.name}`;
      break;
    case "enum":
      s = t.values.length ? t.values.map((v) => JSON.stringify(v)).join(" | ") : "never";
      break;
    case "union":
      s = t.variants.map((v) => tsType(v, prefix)).join(" | ");
      break;
  }
  return t.nullable && s !== "null" && s !== "unknown" ? `${s} | null` : s;
}

function isCompound(t: TypeRef): boolean {
  return !!t.nullable || t.kind === "union" || (t.kind === "enum" && t.values.length > 1);
}

const propKey = (name: string) => (isValidJsIdentifier(name) ? name : JSON.stringify(name));

function jsDoc(lines: (string | undefined)[], indent = ""): string[] {
  const text = lines.filter((l): l is string => l !== undefined).join("\n").replace(/\*\//g, "*\\/").trim();
  if (!text) return [];
  const body = text.split("\n");
  if (body.length === 1) return [`${indent}/** ${body[0]} */`];
  return [`${indent}/**`, ...body.map((l) => (l ? `${indent} * ${l}` : `${indent} *`)), `${indent} */`];
}

function header(spec: ApiSpec): string {
  return `// Code generated by api-sdk-generator from "${spec.title}" v${spec.version}. DO NOT EDIT.`;
}

// ----------------------------------------------------------------- models

function renderModels(spec: ApiSpec): string {
  const out = [header(spec), ""];
  for (const model of spec.models) out.push(...renderModel(model), "");
  if (spec.models.length === 0) out.push("export {};");
  return finalize(out);
}

function renderModel(model: Model): string[] {
  const doc = jsDoc([model.description]);
  switch (model.kind) {
    case "enum":
      return [...doc, `export type ${model.name} = ${tsType({ kind: "enum", values: model.values })};`];
    case "alias":
      return [...doc, `export type ${model.name} = ${tsType(model.type)};`];
    case "object": {
      if (model.properties.length === 0) {
        return [...doc, `export type ${model.name} = Record<string, ${tsType(model.additionalProperties ?? { kind: "primitive", name: "unknown" })}>;`];
      }
      const lines = [...doc, `export interface ${model.name} {`];
      for (const p of model.properties) {
        lines.push(...jsDoc([p.description], "  "));
        lines.push(`  ${propKey(p.name)}${p.required ? "" : "?"}: ${tsType(p.type)};`);
      }
      if (model.additionalProperties) {
        lines.push("  /** Additional properties allowed by the schema. */", "  [key: string]: unknown;");
      }
      lines.push("}");
      return lines;
    }
  }
}

// ----------------------------------------------------------------- client

/** Per-operation generated names, kept clear of model names to avoid export clashes. */
class OperationNames {
  readonly clientClass: string;
  private readonly params = new Map<string, string>();
  private readonly errors = new Map<string, string>();

  constructor(spec: ApiSpec) {
    const taken = new Set(spec.models.map((m) => m.name));
    for (const fixed of ["ApiError", "ClientOptions", "DEFAULT_BASE_URL"]) taken.add(fixed);
    this.clientClass = uniqueName(clientClassName(spec, pascalCase), taken);
    taken.add(this.clientClass);
    for (const op of spec.operations) {
      const base = pascalCase(op.id);
      const p = uniqueName(`${base}Params`, taken);
      taken.add(p);
      const e = uniqueName(`${base}Error`, taken);
      taken.add(e);
      this.params.set(op.id, p);
      this.errors.set(op.id, e);
    }
  }

  paramsType(op: Operation): string {
    return this.params.get(op.id)!;
  }

  errorType(op: Operation): string {
    return this.errors.get(op.id)!;
  }
}

const RUNTIME = `export interface ClientOptions {
  /** Base URL of the API. Defaults to DEFAULT_BASE_URL. */
  baseUrl?: string;
  /** Headers sent with every request, e.g. { Authorization: "Bearer <token>" }. */
  headers?: Record<string, string>;
  /** Custom fetch implementation. Defaults to the global fetch. */
  fetch?: typeof fetch;
}

/**
 * Thrown for every non-2xx response. \`body\` is the parsed response body,
 * typed with the error schema(s) the operation documents.
 */
export class ApiError<TBody = unknown> extends Error {
  readonly status: number;
  readonly body: TBody;
  readonly response: Response;

  constructor(status: number, body: TBody, response: Response) {
    super(\`Request failed with status \${status}\`);
    this.name = "ApiError";
    this.status = status;
    this.body = body;
    this.response = response;
  }
}

type Scalar = string | number | boolean | null | undefined;

interface RequestOptions {
  method: string;
  path: string;
  query?: Record<string, Scalar | readonly Scalar[]>;
  headers?: Record<string, Scalar>;
  body?: unknown;
  contentType?: string;
}

async function readBody(response: Response): Promise<unknown> {
  if (response.status === 204) return undefined;
  const text = await response.text();
  if (!text) return undefined;
  if (/json/i.test(response.headers.get("content-type") ?? "")) {
    try {
      return JSON.parse(text);
    } catch {
      return text;
    }
  }
  return text;
}`;

const REQUEST_METHOD = `  private async request<T>(options: RequestOptions): Promise<T> {
    let url = this.baseUrl + options.path;
    const search = new URLSearchParams();
    for (const [key, value] of Object.entries(options.query ?? {})) {
      const values = Array.isArray(value) ? value : [value];
      for (const item of values) {
        if (item !== undefined && item !== null) search.append(key, String(item));
      }
    }
    const qs = search.toString();
    if (qs) url += \`?\${qs}\`;

    const headers: Record<string, string> = { Accept: "application/json", ...this.headers };
    for (const [key, value] of Object.entries(options.headers ?? {})) {
      if (value !== undefined && value !== null) headers[key] = String(value);
    }

    let body: BodyInit | undefined;
    if (options.body !== undefined) {
      if (options.contentType && /json/i.test(options.contentType)) {
        headers["Content-Type"] = options.contentType;
        body = JSON.stringify(options.body);
      } else {
        // Non-JSON bodies (FormData, Blob, string...) are sent as-is; fetch sets multipart boundaries.
        if (options.contentType && !options.contentType.startsWith("multipart/")) {
          headers["Content-Type"] = options.contentType;
        }
        body = options.body as BodyInit;
      }
    }

    const response = await this.fetchImpl(url, { method: options.method, headers, body });
    const data = await readBody(response);
    if (!response.ok) throw new ApiError(response.status, data, response);
    return data as T;
  }`;

function renderClient(spec: ApiSpec, names: OperationNames): string {
  const out: string[] = [header(spec), ""];
  if (spec.models.length) out.push('import type * as M from "./models.js";', "");
  out.push(`/** Default base URL, taken from the spec's first server entry. */`);
  out.push(`export const DEFAULT_BASE_URL = ${JSON.stringify(spec.baseUrl)};`, "");
  out.push(RUNTIME, "");

  for (const op of spec.operations) {
    if (op.parameters.length) {
      out.push(`/** Parameters for {@link ${names.clientClass}.${camelCase(op.id)}}. */`);
      out.push(`export interface ${names.paramsType(op)} {`);
      for (const p of op.parameters) {
        out.push(...jsDoc([p.description, p.name !== camelCase(p.name) ? `Sent as \`${p.name}\` (${p.in}).` : undefined], "  "));
        out.push(`  ${propKey(camelCase(p.name))}${p.required ? "" : "?"}: ${tsType(p.type, "M.")};`);
      }
      out.push("}", "");
    }
    const errType = op.errorTypes.length ? op.errorTypes.map((t) => tsType(t, "M.")).join(" | ") : "unknown";
    out.push(`/** Body of an {@link ApiError} thrown by {@link ${names.clientClass}.${camelCase(op.id)}}. */`);
    out.push(`export type ${names.errorType(op)} = ${errType};`, "");
  }

  out.push(...jsDoc([`Typed client for ${spec.title} v${spec.version}.`]));
  out.push(`export class ${names.clientClass} {`);
  out.push("  private readonly baseUrl: string;");
  out.push("  private readonly headers: Record<string, string>;");
  out.push("  private readonly fetchImpl: typeof fetch;", "");
  out.push("  constructor(options: ClientOptions = {}) {");
  out.push('    this.baseUrl = (options.baseUrl ?? DEFAULT_BASE_URL).replace(/\\/+$/, "");');
  out.push("    this.headers = { ...options.headers };");
  out.push("    this.fetchImpl = options.fetch ?? globalThis.fetch.bind(globalThis);");
  out.push("  }", "");

  for (const op of spec.operations) out.push(...renderMethod(op, names), "");
  out.push(REQUEST_METHOD, "}");
  return finalize(out);
}

function renderMethod(op: Operation, names: OperationNames): string[] {
  const returnType = op.successType ? tsType(op.successType, "M.") : "void";
  const hasParams = op.parameters.length > 0;
  const paramsRequired = op.parameters.some((p) => p.required);
  const args: string[] = [];
  if (hasParams && paramsRequired) args.push(`params: ${names.paramsType(op)}`);
  if (op.requestBody) args.push(`body${op.requestBody.required ? "" : "?"}: ${tsType(op.requestBody.type, "M.")}`);
  if (hasParams && !paramsRequired) args.push(`params: ${names.paramsType(op)} = {}`);

  const accessor = (name: string) => {
    const key = camelCase(name);
    return isValidJsIdentifier(key) ? `params.${key}` : `params[${JSON.stringify(key)}]`;
  };
  const escaped = op.path.replace(/\\/g, "\\\\").replace(/`/g, "\\`").replace(/\$\{/g, "\\${");
  const path = escaped.replace(/\{([^}]+)\}/g, (match, name: string) => {
    const p = op.parameters.find((x) => x.in === "path" && x.name === name);
    return p ? `\${encodeURIComponent(String(${accessor(name)}))}` : match;
  });
  const group = (where: string) =>
    op.parameters
      .filter((p) => p.in === where)
      .map((p) => `${propKey(p.name)}: ${accessor(p.name)}`)
      .join(", ");

  const lines = jsDoc(
    [
      op.summary,
      op.description && op.description !== op.summary ? `\n${op.description}` : undefined,
      `\n\`${op.method.toUpperCase()} ${op.path}\``,
      `@throws {ApiError<${names.errorType(op)}>} when the server responds with a non-2xx status.`,
      op.deprecated ? "@deprecated" : undefined,
    ],
    "  ",
  );
  lines.push(`  async ${camelCase(op.id)}(${args.join(", ")}): Promise<${returnType}> {`);
  lines.push(`    return this.request<${returnType}>({`);
  lines.push(`      method: ${JSON.stringify(op.method.toUpperCase())},`);
  lines.push(`      path: \`${path}\`,`);
  if (group("query")) lines.push(`      query: { ${group("query")} },`);
  if (group("header")) lines.push(`      headers: { ${group("header")} },`);
  if (op.requestBody) {
    lines.push("      body,");
    lines.push(`      contentType: ${JSON.stringify(op.requestBody.contentType)},`);
  }
  lines.push("    });", "  }");
  return lines;
}

// ------------------------------------------------------------------- docs

function sample(t: TypeRef, spec: ApiSpec): string {
  switch (t.kind) {
    case "primitive":
      return { string: '"string"', integer: "1", number: "1.5", boolean: "true", null: "null", unknown: "{}" }[t.name];
    case "enum":
      return JSON.stringify(t.values[0] ?? null);
    case "array":
      return `[${sample(t.items, spec)}]`;
    case "map":
      return "{}";
    case "union":
      return sample(t.variants[0], spec);
    case "ref": {
      const m = spec.models.find((x) => x.name === t.name);
      if (m?.kind === "enum") return JSON.stringify(m.values[0] ?? null);
      if (m?.kind === "alias") return sample(m.type, spec);
      return "{ /* ... */ }";
    }
  }
}

function docStyle(spec: ApiSpec): DocStyle {
  const names = new OperationNames(spec);
  return {
    language: "TypeScript",
    fence: "ts",
    renderType: (t) => tsType(t),
    methodName: (op) => camelCase(op.id),
    paramName: (name) => camelCase(name),
    setup: [
      `import { ${names.clientClass}, ApiError } from "./sdk"; // path to the generated folder`,
      "",
      `const client = new ${names.clientClass}({`,
      `  baseUrl: ${JSON.stringify(spec.baseUrl || "https://api.example.com")},`,
      '  headers: { Authorization: "Bearer <token>" },',
      "});",
    ].join("\n"),
    example(op) {
      const lines: string[] = [];
      const args: string[] = [];
      const required = op.parameters.filter((p) => p.required);
      if (required.length) {
        args.push(`{ ${required.map((p) => `${propKey(camelCase(p.name))}: ${sample(p.type, spec)}`).join(", ")} }`);
      }
      if (op.requestBody) {
        lines.push(`const body: ${tsType(op.requestBody.type)} = ${sample(op.requestBody.type, spec)};`);
        args.push("body");
      }
      lines.push("try {");
      const call = `client.${camelCase(op.id)}(${args.join(", ")})`;
      lines.push(op.successType ? `  const result = await ${call};` : `  await ${call};`);
      lines.push("} catch (err) {");
      lines.push(`  if (err instanceof ApiError) console.error(err.status, err.body);`);
      lines.push("}");
      return lines.join("\n");
    },
  };
}
